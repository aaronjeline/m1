#!/usr/bin/env python3
"""Generate the no-panic proof of a *read-only* function with a standard frame.

    targets/cedar-check/gen-ro-proof.py NAME DOC CALLEE... > Examples/Cedar/NoPanic/Fn/NAME/Proof.lean

Reads `Examples/Cedar/NoPanic/Fn/NAME/Code.lean` (from `extract-fn.py`) and
emits a proof by the whole-body invariant (`body_loop` + `body_case`, see
`Frame.lean`): the layout is read off the prologue (`stp`s / `sub sp` up to
`add x29, sp, #k`), the body is every instruction but the prologue and the
epilogues (`ldp x29, x30` up to `ret`).

Each CALLEE is `ext_i=Module:room` for a callee proved in `Fn/Module` with
contract `Module.np H lo top Self p hs C hM` and stack room `room`, or
`ext_i=memcmp` for libc's `memcmp`. The contract proved: no precondition but
stack room; never panics; writes only the free stack. Only for functions that
store nothing outside their frame (the generated proof fails otherwise).
"""
import re
import sys

NAME, DOC = sys.argv[1], sys.argv[2]
CALLEES = sys.argv[3:]
src = open(f'Examples/Cedar/NoPanic/Fn/{NAME}/Code.lean').read()
insns = [(int(a, 16), d.strip()) for a, d in re.findall(r'#32[, ] -- 0x([0-9a-f]+): (.*)', src)]
base = insns[0][0]

# Prologue and layout.
size, slots, pro_end = None, [], None
for i, (a, d) in enumerate(insns):
    m = re.match(r'stp (x\d+), (x\d+), \[sp, #-0x([0-9a-f]+)\]!', d)
    if m:
        size = int(m.group(3), 16)
        slots += [(m.group(1), 0), (m.group(2), 8)]
        continue
    m = re.match(r'sub sp, sp, #0x([0-9a-f]+)', d)
    if m:
        size = int(m.group(1), 16) + (size or 0)
        continue
    m = re.match(r'stp (x\d+), (x\d+), \[sp, #0x([0-9a-f]+)\]$', d)
    if m:
        o = int(m.group(3), 16)
        slots += [(m.group(1), o), (m.group(2), o + 8)]
        continue
    if re.match(r'add x29, sp, #0x', d):
        pro_end = insns[i + 1][0]
        break
    raise SystemExit(f'unexpected prologue instruction at {a:#x}: {d}')
assert size is not None and pro_end is not None

# Epilogues: from `ldp x29, x30` to `ret` / a tail call.
excl = set(a for a, _ in insns if a < pro_end)
epis = []
i = 0
while i < len(insns):
    a, d = insns[i]
    if d.startswith('ldp x29, x30'):
        epis.append(a)
        while True:
            excl.add(insns[i][0])
            if insns[i][1].startswith('ret') or re.match(r'b 0x', insns[i][1]):
                break
            i += 1
    i += 1
body = [a for a, _ in insns if a not in excl]

layout = ', '.join(f'({r[1:]}#5, {o:#x})' for r, o in slots)
room = 0
calls, imports, haves, exts = [], [], [], []
for c in CALLEES:
    e, spec = c.split('=')
    if spec == 'memcmp':
        calls.append('(C.memcmp n)')
        exts.append(f'{e} = libcMemcmp')
    else:
        mod, r = spec.split(':')
        room = max(room, int(r, 0))
        imports.append(f'import Examples.Cedar.NoPanic.Fn.{mod}.Proof')
        haves.append(f'  have {mod}_np := {mod}.np H lo top Self p h{mod} C hM')
        calls.append(f'({mod}_np n)')
        exts.append(f'{e} = {mod}.sym_fn')
hyps = ''.join(f' (h{c.split("=")[1].split(":")[0]} : p.Extends {c.split("=")[1].split(":")[0]}.prog)'
               for c in CALLEES if not c.endswith('=memcmp'))
nl = '\n'
print(f'''import Examples.Cedar.NoPanic.Fn.{NAME}.Code
import Examples.Cedar.NoPanic.Frame
{nl.join(imports)}

/-!
# {DOC} at `{base:#x}`

Generated by `targets/cedar-check/gen-ro-proof.py` (a read-only function with a
standard frame): no precondition besides stack room; it never panics and
writes only the free stack. Proof: the whole-body invariant (`body_loop`), one
`body_case` per instruction of the body.
-/

set_option linter.unusedSimpArgs false

namespace Examples.Cedar.NoPanic.Fn.{NAME}
open M1 Examples.Cedar.Eval Examples.Cedar.NoPanic

variable (H : Heap) (lo top Self : BitVec 64)

theorem ext_eqs : {' ∧ '.join(exts) if exts else 'True'} := {'⟨' + ', '.join(['rfl'] * len(exts)) + '⟩' if len(exts) > 1 else ('rfl' if exts else 'trivial')}

def L : Layout := ⟨{size:#x}, [{layout}], []⟩

/-- The body: every instruction but the prologue and the epilogues (at {', '.join(f'`{a:#x}`' for a in epis)}). -/
def body : List (BitVec 64) := [{', '.join(f'{a:#x}#64' for a in body)}]

set_option maxHeartbeats 4000000 in
theorem np (p : Program) (hp : p.Extends prog){hyps} (C : LibC H p lo top Self) (hM : MemFacts H lo top) :
    NP p top sym_fn (Room lo top ({size:#x} + {room:#x})) (fun _ => 0#64) 0 (fun s s' => OnlyWrites lo 0#64 0 s s') := by
{nl.join(haves)}
  rintro n s hpc hst ⟨hal, hr, hr'⟩
  simp only [sym_fn, BitVec.ofNat_eq_ofNat] at *
  have ht := hM.tlvOffStack
  have hr0 : {size:#x} ≤ (s.sp - lo).toNat := by omega
  frame_enter L lo top 0#64 0 {pro_end:#x}#64 as s1 E
  refine body_loop body ⟨E.frame, E.mem.mono fun x hx => Or.inl (frame_freeStack (L := L) hr0 hr' hx), E.status⟩
    (by rw [E.pc]; decide) ?_
  clear E hpc hst
  intro n s2 hI hpc
  simp only [body, List.mem_cons, List.mem_nil_iff, or_false] at hpc
  split_ors hpc
  all_goals body_case L body hI hpc {', '.join(calls)}

end Examples.Cedar.NoPanic.Fn.{NAME}''')
